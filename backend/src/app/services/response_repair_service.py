from app.llm.factory import get_llm_provider

class ResponseRepairService:
    def __init__(self):
        self.provider = get_llm_provider()

    async def repair(
        self,
        question: str,
        context: str,
        answer: str,
        validation_report: str,
    ) -> str:

        prompt = f"""
You are correcting an answer generated by a RAG system.

Question:
{question}
Retrieved Documents:
{context}
Original Answer:
{answer}
Validation Report:
{validation_report}

Instructions:
- Remove unsupported claims.
- Keep supported information.
- Do not invent new information.
- Do not change writing style.
- Do not mention corrections.
- Do not mention validation.
- Produce the corrected answer only.
"""
        repaired = await self.provider.generate(prompt)
        return repaired.strip()

_repair = None

def get_response_repair_service():
    global _repair

    if _repair is None:
        _repair = ResponseRepairService()

    return _repair